    @ParameterizedTest
    @CsvSource({"root,true", "root,false", "app,true", "app,false"})
    void strictRetainedSourcesRejectSameOwnerDuplicates(
            String owner, boolean identical, @TempDir Path workspace) throws Exception {
        String prefix = owner.equals("root") ? "main/java/" : "app/src/main/java_clean/";
        String first = prefix + "first/Duplicate.java";
        String second = prefix + "second/Duplicate.java";
        write(workspace.resolve(first), "package fixture; public class Duplicate {}\n");
        write(workspace.resolve(second), identical
                ? "package fixture; public class Duplicate {}\n"
                : "package fixture; public class Duplicate { int changed; }\n");

        ScriptResult result = runStrictScript(workspace, owner, List.of(first, second));

        assertTrue(result.exitCode() != 0, "retained duplicate must reject");
        assertTrue(result.output().contains("SOURCE_HYGIENE_DUPLICATE"), result.output());
        assertFalse(Files.exists(workspace.resolve("__reports__/context-purity-decisions.tsv")));
    }

    @Test
    void strictRetainedSourcesIgnoreExcludedAndInactiveCopies(@TempDir Path workspace) throws Exception {
        String active = "main/java/first/Duplicate.java";
        String source = "package fixture; public class Duplicate {}\n";
        write(workspace.resolve(active), source);
        write(workspace.resolve("main/java/excluded/Duplicate.java"), source);
        write(workspace.resolve("app/src/main/java/inactive/Duplicate.java"), source);

        ScriptResult result = runStrictScript(workspace, "root", List.of(active));

        assertEquals(0, result.exitCode(), result.output());
        assertTrue(result.output().contains("retainedFiles=1"), result.output());
        assertFalse(Files.exists(workspace.resolve("__reports__/context-purity-decisions.tsv")));
    }

    @Test
    void strictRetainedSourcesPreserveCaseSensitiveFqcnAndBom(@TempDir Path workspace) throws Exception {
        String first = "main/java/first/Example.java";
        String second = "main/java/second/Example.java";
        writeUtf8Bom(workspace.resolve(first), "package fixture.upper; public class Example {}\n");
        write(workspace.resolve(second), "package fixture.Upper; public class Example {}\n");

        ScriptResult result = runStrictScript(workspace, "root", List.of(first, second));

        assertEquals(0, result.exitCode(), result.output());
        assertTrue(result.output().contains("retainedFiles=2"), result.output());
    }

    @ParameterizedTest
    @CsvSource({"../outside.java", "app/src/main/java/inactive/Example.java"})
    void strictRetainedSourcesRejectPathsOutsideDeclaredOwner(
            String source, @TempDir Path workspace) throws Exception {
        ScriptResult result = runStrictScript(workspace, "root", List.of(source));

        assertTrue(result.exitCode() != 0);
        assertTrue(result.output().contains("SOURCE_HYGIENE_PATH"), result.output());
    }

    private record ScriptResult(int exitCode, String output) {}

    private static ScriptResult runStrictScript(Path workspace, String owner, List<String> files)
            throws Exception {
        Path manifest = workspace.resolve("retained-sources.json");
        String entries = files.stream().map(path -> "\"" + path + "\"")
                .collect(java.util.stream.Collectors.joining(","));
        write(manifest, "{\"" + owner + "\":[" + entries + "]}");
        Path log = workspace.resolve("strict-output.log");
        Process process = new ProcessBuilder("powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                "-File", Path.of("tools/context_purity_score.ps1").toAbsolutePath().toString(),
                "-Workspace", workspace.toString(), "-ActiveSourceManifest", manifest.toString())
                .redirectErrorStream(true).redirectOutput(log.toFile()).start();
        try {
            assertTrue(process.waitFor(30, TimeUnit.SECONDS), "strict source verification timed out");
            return new ScriptResult(process.exitValue(),
                    new String(Files.readAllBytes(log), StandardCharsets.UTF_8));
        } finally {
            if (process.isAlive()) {
                process.destroyForcibly();
                process.waitFor(5, TimeUnit.SECONDS);
            }
        }
    }

    private static void runScript(Path workspace) throws Exception {
        Path script = Path.of("tools/context_purity_score.ps1").toAbsolutePath();
        Process process = new ProcessBuilder(
                "powershell",
                "-NoProfile",
                "-ExecutionPolicy",
                "Bypass",
                "-File",
                script.toString(),
                "-Workspace",
                workspace.toString(),
                "-MaxItems",
                "100")
                .redirectErrorStream(true)
                .start();
        boolean finished = process.waitFor(30, TimeUnit.SECONDS);
        if (!finished) {
            process.destroyForcibly();
        }
        String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        assertTrue(finished, "context purity script timed out: " + output);
        assertEquals(0, process.exitValue(), output);
    }

    private static Map<String, Map<String, String>> rowsByPath(List<String> lines) {
        List<String> header = List.of(lines.get(0).split("\\t", -1));
        Map<String, Map<String, String>> rows = new LinkedHashMap<>();
        for (String line : lines.subList(1, lines.size())) {
            List<String> values = new ArrayList<>(List.of(line.split("\\t", -1)));
            assertEquals(header.size(), values.size(), line);
            Map<String, String> row = new LinkedHashMap<>();
            for (int i = 0; i < header.size(); i++) {
                row.put(header.get(i), values.get(i));
            }
            rows.put(row.get("source_path"), row);
        }
        return rows;
    }

    private static void assertDecision(
            Map<String, Map<String, String>> rows,
            String path,
            String decision,
            String reason) {
        Map<String, String> row = rows.get(path);
        assertNotNull(row, path);
        assertEquals(decision, row.get("decision"), path);
        assertEquals(reason, row.get("reason"), path);
    }

    private static void assertField(
            Map<String, Map<String, String>> rows,
            String path,
            String field,
            String expected) {
        Map<String, String> row = rows.get(path);
        assertNotNull(row, path);
        assertEquals(expected, row.get(field), path + " field=" + field);
    }

    private static void write(Path path, String content) throws IOException {
        Files.createDirectories(path.getParent());
        Files.writeString(path, content, StandardCharsets.UTF_8);
    }

    private static void writeUtf8Bom(Path path, String content) throws IOException {
        Files.createDirectories(path.getParent());
        byte[] source = content.getBytes(StandardCharsets.UTF_8);
        byte[] bytes = new byte[source.length + 3];
        bytes[0] = (byte) 0xEF;
        bytes[1] = (byte) 0xBB;
        bytes[2] = (byte) 0xBF;
        System.arraycopy(source, 0, bytes, 3, source.length);
        Files.write(path, bytes);
    }
