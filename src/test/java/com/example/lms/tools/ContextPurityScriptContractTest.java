    @Test
    void boundedReportAtomicallyWritesDeterministicDecisionTsv(@TempDir Path workspace) throws Exception {
        write(workspace.resolve("main/java/example/Active.java"), "package example; class Active {}\n");
        write(workspace.resolve("main/java/example/Leaked.class"), "generated bytecode\n");
        write(workspace.resolve("app/src/main/resources/application.yml"), "feature: true\n");
        write(workspace.resolve("agent-prompts/out/generated.prompt"), "generated\n");
        write(workspace.resolve("agent-prompts/manual-note.md"), "manual review\n");
        write(workspace.resolve("agent-prompts/legacy.bak"), "uncertain backup\n");
        write(workspace.resolve("docs/ai-memory/Dynamic_RAG_Orchestration_Platform.memory.md"),
                "canonical memory\n");
        write(workspace.resolve(".agents/skills/sample/SKILL.md"), "canonical skill\n");

        Path report = workspace.resolve("__reports__/context-purity-decisions.tsv");
        runScript(workspace);
        byte[] first = Files.readAllBytes(report);
        runScript(workspace);
        byte[] second = Files.readAllBytes(report);

        assertTrue(Arrays.equals(first, second), "same bounded workspace must produce identical TSV bytes");
        List<String> lines = Files.readAllLines(report, StandardCharsets.UTF_8);
        assertFalse(lines.isEmpty());
        assertEquals(List.of(
                        "source_path",
                        "source_set_role",
                        "active_weight",
                        "generated_score",
                        "legacy_score",
                        "duplicate_score",
                        "delete_score",
                        "memory_value",
                        "decision",
                        "reason"),
                List.of(lines.get(0).split("\\t", -1)));

        Map<String, Map<String, String>> rows = rowsByPath(lines);
        assertDecision(rows, "main\\java\\example\\Active.java", "KEEP", "active_sourceset");
        assertDecision(rows, "main\\java\\example\\Leaked.class", "DELETE", "generated_artifact");
        assertDecision(rows, "app\\src\\main\\resources\\application.yml", "KEEP", "active_sourceset");
        assertDecision(rows, "agent-prompts\\out\\generated.prompt", "DELETE", "generated_artifact");
        assertDecision(rows, "agent-prompts\\manual-note.md", "EVIDENCE_NEEDED", "needs_owner_review");
        assertDecision(rows, "agent-prompts\\legacy.bak", "QUARANTINE", "uncertain_legacy_artifact");
        assertDecision(rows,
                "docs\\ai-memory\\Dynamic_RAG_Orchestration_Platform.memory.md",
                "KEEP",
                "canonical_memory_doc");
        assertDecision(rows, ".agents\\skills\\sample\\SKILL.md", "KEEP", "canonical_skill");

        Set<String> allowed = Set.of("KEEP", "DELETE", "QUARANTINE", "EVIDENCE_NEEDED");
        assertTrue(rows.values().stream().allMatch(row -> allowed.contains(row.get("decision"))));
        assertTrue(rows.values().stream().noneMatch(row -> "KEEP_AND_INGEST".equals(row.get("decision"))));
        try (var files = Files.list(report.getParent())) {
            assertTrue(files.noneMatch(path -> {
                        String name = path.getFileName().toString();
                        return name.contains(".tmp-") || name.contains(".backup-");
                    }),
                    "atomic writer must not leave temporary or backup report files");
        }
    }

